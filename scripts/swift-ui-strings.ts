// Generates the Mac app's String Catalog and its typed accessors from the setup page catalogs
// (web/src/i18n/*.ts) plus the app-only text (mac/App/app-strings.ts):
//   mac/App/Localizable.xcstrings            (the catalog; compiled into <lang>.lproj by build-app.sh)
//   mac/Sources/HomebotUI/Strings.generated.swift
// Usage: node scripts/swift-ui-strings.ts
// Keys are flattened: nested tables become "errors.auth", lists "siriWhere.0". A language missing
// a key, or defining one English lacks, stops the generator.
import { writeFileSync } from "node:fs";
import { STRINGS } from "../web/src/i18n/index.ts";
import { APP_STRINGS, en as appEn } from "../mac/App/app-strings.ts";

const LANGS = ["en", "es", "fr", "de", "it", "pt-BR", "ru", "ja", "ko", "zh-Hans", "zh-Hant"] as const;
const root = new URL("..", import.meta.url).pathname;

function flatten(obj: Record<string, unknown>, prefix = "", out: Record<string, string> = {}): Record<string, string> {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (typeof v === "string") out[key] = v;
    else if (Array.isArray(v)) v.forEach((s, i) => (out[`${key}.${i}`] = String(s)));
    else if (v && typeof v === "object") flatten(v as Record<string, unknown>, key, out);
  }
  return out;
}

const tables: Record<string, Record<string, string>> = {};
for (const l of LANGS) {
  const web = flatten(STRINGS[l] as unknown as Record<string, unknown>);
  const app = APP_STRINGS[l];
  if (!app) throw new Error(`app strings: no ${l}`);
  for (const k of Object.keys(app)) if (k in web) throw new Error(`app key ${k} collides with a web key`);
  tables[l] = { ...web, ...app };
}
const keys = Object.keys(tables.en!).sort();
for (const l of LANGS) {
  const have = Object.keys(tables[l]!);
  const missing = keys.filter((k) => !(k in tables[l]!));
  const extra = have.filter((k) => !(k in tables.en!));
  if (missing.length || extra.length) throw new Error(`${l}: missing ${missing.join(", ") || "-"}; extra ${extra.join(", ") || "-"}`);
}

const catalog = {
  sourceLanguage: "en",
  strings: Object.fromEntries(
    keys.map((k) => [
      k,
      {
        extractionState: "manual",
        localizations: Object.fromEntries(LANGS.map((l) => [l, { stringUnit: { state: "translated", value: tables[l]![k] } }])),
      },
    ]),
  ),
  version: "1.0",
};
writeFileSync(`${root}mac/App/Localizable.xcstrings`, JSON.stringify(catalog, null, 2) + "\n");

// Typed accessors: plain keys become properties; lists become [String]; tables become lookups.
const ident = (k: string) => k.replace(/[^A-Za-z0-9_]/g, "_");
const plain = keys.filter((k) => !k.includes("."));
const lists = new Map<string, number>();
const tablesByName = new Set<string>();
for (const k of keys) {
  const [head, rest] = [k.slice(0, k.indexOf(".")), k.slice(k.indexOf(".") + 1)];
  if (!k.includes(".")) continue;
  if (/^\d+$/.test(rest)) lists.set(head, Math.max(lists.get(head) ?? 0, Number(rest) + 1));
  else tablesByName.add(head);
}
const lines = [
  "// Generated by scripts/swift-ui-strings.ts from web/src/i18n/*.ts and mac/App/app-strings.ts.",
  "// Do not edit; change the catalogs and run `node scripts/swift-ui-strings.ts`.",
  "",
  "public extension Tr {",
  ...plain.map((k) => `  var ${ident(k)}: String { self[${JSON.stringify(k)}] }`),
  ...[...lists].map(([k, n]) => `  var ${ident(k)}: [String] { (0..<${n}).map { self["${k}.\\($0)"] } }`),
  ...[...tablesByName].sort().map((t) => `  /// The "${t}" table; nil for an unknown code.\n  func ${ident(t)}(_ code: String) -> String? { lookup("${t}.\\(code)") }`),
  "}",
  "",
  "public enum UIStringKeys {",
  `  public static let all: [String] = [${keys.map((k) => JSON.stringify(k)).join(", ")}]`,
  `  public static let appOnly: Set<String> = [${Object.keys(appEn).sort().map((k) => JSON.stringify(k)).join(", ")}]`,
  "}",
  "",
];
writeFileSync(`${root}mac/Sources/HomebotUI/Strings.generated.swift`, lines.join("\n"));
console.log(`${keys.length} keys × ${LANGS.length} languages`);
